/* Translate every element marked with data-i18n. */

const languageSelect = document.getElementById("language");

function setLanguage(language) {
  const lang = language === "en" ? "en" : "ko";
  const dictionary = translations[lang];

  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;

    if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
      element.innerHTML = dictionary[key];
    }
  });

  languageSelect.value = lang;

  document.title = lang === "ko"
    ? "더 그릴 | 대전 한국식 바비큐"
    : "The Grill | Korean BBQ in Daejeon";

  try {
    localStorage.setItem("the-grill-language", lang);
  } catch (error) {
    // Language switching still works without local storage.
  }
}

languageSelect.addEventListener("change", (event) => {
  setLanguage(event.target.value);
});

/* Start in Korean, unless the visitor has already selected a language. */

let savedLanguage = "ko";

try {
  savedLanguage = localStorage.getItem("the-grill-language") || "ko";
} catch (error) {
  savedLanguage = "ko";
}

setLanguage(savedLanguage);

/* Responsive navigation. */

const menuToggle = document.getElementById("menuToggle");
const navLinks = document.getElementById("navLinks");

function closeMenu() {
  navLinks.classList.remove("open");
  menuToggle.classList.remove("open");
  menuToggle.setAttribute("aria-expanded", "false");
  menuToggle.setAttribute("aria-label", "Open navigation");
}

menuToggle.addEventListener("click", () => {
  const isOpen = navLinks.classList.toggle("open");

  menuToggle.classList.toggle("open", isOpen);
  menuToggle.setAttribute("aria-expanded", String(isOpen));
  menuToggle.setAttribute(
    "aria-label",
    isOpen ? "Close navigation" : "Open navigation"
  );
});

navLinks.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", closeMenu);
});

document.addEventListener("click", (event) => {
  if (
    !navLinks.contains(event.target) &&
    !menuToggle.contains(event.target)
  ) {
    closeMenu();
  }
});

window.addEventListener("resize", () => {
  if (window.innerWidth > 760) {
    closeMenu();
  }
});

